def main():
    os.makedirs(OUTDIR, exist_ok=True)

    print("[thesis_analysis] Loading data...")
    t, ref_deg, controllers = load_data()
    print(f"  Controllers: {list(controllers)}")
    print(f"  Duration: {t[-1]:.0f} s,  samples: {len(t)}")

    print("[thesis_analysis] Computing full performance metrics...")
    full_metrics = compute_full_metrics(t, ref_deg, controllers)

    print("[thesis_analysis] Root cause quantification...")
    root_cause = root_cause_analysis(t, ref_deg, controllers, full_metrics)

    print("[thesis_analysis] Statistical significance tests...")
    stat_tests = statistical_tests(t, ref_deg, controllers)

    print("[thesis_analysis] Segment decomposition...")
    seg_data = compute_segments(t, ref_deg, controllers)

    print("[thesis_analysis] Generating figures...")
    generate_figures(t, ref_deg, controllers, full_metrics, seg_data, OUTDIR)

    print("[thesis_analysis] Depth channel...")
    ref_depth, depth_ctrl = load_depth_data()
    depth_rows = None
    if depth_ctrl:
        d_regimes, d_seg, depth_rows = compute_depth_metrics(t, ref_depth, depth_ctrl)
        generate_depth_figures(t, ref_depth, depth_ctrl, d_regimes, d_seg, OUTDIR)
        R.write_csv(depth_rows,
                    ["controller", "rmse_m", "transient_rmse_m", "settled_rmse_m",
                     "mae_m", "p95_m", "max_m"],
                    os.path.join(OUTDIR, "thesis_depth_metrics.csv"))
    else:
        print("  no depth columns in the CSVs — rerun run_remus100_comparison "
              "and compare_nmpc_patch to get the depth figures")

    print("[thesis_analysis] Writing CSV tables...")
    write_metric_csvs(full_metrics, seg_data, stat_tests, OUTDIR)

    print("[thesis_analysis] Writing Markdown report...")
    generate_report(t, ref_deg, controllers, full_metrics, root_cause, stat_tests,
                    seg_data, OUTDIR)

    print("[thesis_analysis] Generating solver timing figures...")
    generate_timing_figures(OUTDIR)

    # Console summary table
    print("\n" + "=" * 70)
    print("  HEADING RMSE SUMMARY (°)")
    print(f"  {'Controller':35s} {'Aggregate':>10s} {'Transient':>10s} {'Settled':>10s}")
    print("  " + "-" * 67)
    for name, fm in full_metrics.items():
        print(f"  {name:35s} "
              f"{fm['aggregate']['rmse']:>10.2f} "
              f"{fm['transient']['rmse']:>10.2f} "
              f"{fm['settled']['rmse']:>10.3f}")
    print("=" * 70)
    if depth_rows:
        print("\n  DEPTH RMSE SUMMARY (m)")
        print(f"  {'Controller':35s} {'Aggregate':>10s} {'Transient':>10s} {'Settled':>10s}")
        print("  " + "-" * 67)
        for r in depth_rows:
            print(f"  {r['controller']:35s} "
                  f"{r['rmse_m']:>10.3f} "
                  f"{r['transient_rmse_m']:>10.3f} "
                  f"{r['settled_rmse_m']:>10.4f}")
        print("=" * 70)
    if stat_tests:
        print("\n  STATISTICAL TESTS (per-segment MAE, n=9 segments)")
        for cmp in stat_tests:
            p = cmp.get("paired_t_p", float("nan"))
            d = cmp.get("cohen_dz", float("nan"))
            sig = "**" if isinstance(p, float) and not math.isnan(p) and p < 0.05 else "  "
            print(f"  {sig}{cmp['label_a']} vs {cmp['label_b']}: "
                  f"Δ={cmp['mean_diff']:.2f}°, "
                  f"CI=[{cmp.get('ci_low_95', float('nan')):.2f}, "
                  f"{cmp.get('ci_high_95', float('nan')):.2f}], "
                  f"t-p={p:.4f}, d_z={d:.3f}{sig}")

    print(f"\n[thesis_analysis] Done.  Output -> {OUTDIR}")
    print("  thesis_report.md")
    print("  thesis_full_metrics.csv")
    print("  thesis_stat_tests.csv")
    print("  thesis_regime_comparison.png")
    print("  thesis_error_ecdf.png")
    print("  thesis_segment_breakdown.png")
    print("  thesis_zoom_reversal.png")
    print("  thesis_zoom_depthcoupling.png")
    print("  thesis_mission_overview.png")
    print("  thesis_solver_timeline.png")
    print("  thesis_solver_distribution.png")
    print("  thesis_solver_stats.csv")


if __name__ == "__main__":
    main()
