def load_solve_times():
    """Load controller solve times from the Scenario 6 CSV.

    Returns (mission_time_s, nmpc_ms, pid50_ms, pid5_ms).
    Any missing column returns None for that array.
    """
    import pandas as pd
    path = os.path.join(RESULTS, "nmpc_solve_times_s6.csv")
    if not os.path.exists(path):
        return None, None, None, None
    df = pd.read_csv(path)

    def _col(name):
        if name not in df.columns:
            return None
        vals = pd.to_numeric(df[name], errors="coerce").values
        return vals[~np.isnan(vals)] if np.any(~np.isnan(vals)) else None

    t_ms   = df["mission_time_s"].values
    nmpc   = _col("nmpc_solve_time_ms")
    pid50  = _col("pid50_solve_time_ms")
    pid5   = _col("pid5_solve_time_ms")
    # Legacy column name (older CSV)
    if pid50 is None and pid5 is None:
        pid50 = _col("pid_solve_time_ms")
    return t_ms, nmpc, pid50, pid5


