#  Statistical significance
# --------------------------------------------------------------------------- #
def statistical_tests(t, ref_deg, controllers):
    """Paired statistical tests across mission segments.

    Each of the 9 segments yields one per-controller MAE observation → valid
    paired comparison with n=9.  Computes:
      - paired t-test (p-value)
      - Wilcoxon signed-rank (p-value, if scipy present)
      - Cohen's d_z effect size
      - 95% confidence interval on the mean MAE difference
    """
    ref_rad = ref_deg * D2R
    # per-segment MAE for each controller
    seg_mae = {}
    for name, d in controllers.items():
        sig_rad = d["heading_cont_deg"] * D2R
        rows = M.segment_decompose(t, sig_rad, ref_rad, BOUNDS, angular=True)
        seg_mae[name] = [r["mae"] * R2D for r in rows]

    names = list(controllers)
    comparisons = []
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            cmp = M.paired_comparison(seg_mae[a], seg_mae[b], labels=(a, b))
            # 95% CI on mean difference (Student-t, df = n-1 = 8)
            d_arr = np.array(seg_mae[a]) - np.array(seg_mae[b])
            n_obs = len(d_arr)
            sem = np.std(d_arr, ddof=1) / max(np.sqrt(n_obs), 1e-9)
            try:
                from scipy import stats as _sps
                tcrit = float(_sps.t.ppf(0.975, df=n_obs - 1))
            except Exception:
                tcrit = 2.306  # t_{0.975, df=8} for n=9 segments
            cmp["ci_low_95"]  = cmp["mean_diff"] - tcrit * sem
            cmp["ci_high_95"] = cmp["mean_diff"] + tcrit * sem
            cmp["n_segments"] = n_obs
            comparisons.append(cmp)
    return comparisons


# --------------------------------------------------------------------------- #
#  Segment decomposition (for figures and tables)
# --------------------------------------------------------------------------- #
def compute_segments(t, ref_deg, controllers):
    ref_rad = ref_deg * D2R
    seg = {}
    for name, d in controllers.items():
        sig_rad = d["heading_cont_deg"] * D2R
        rows = M.segment_decompose(t, sig_rad, ref_rad, BOUNDS, angular=True,
                                   steady_frac=0.4)
        for r in rows:
            for k in ("iae", "mae", "rmse", "max_abs", "steady_state"):
                r[k] *= R2D
        seg[name] = rows
    return seg


# --------------------------------------------------------------------------- #
#  Turn labels for segments
# --------------------------------------------------------------------------- #
def _turn_labels():
    labels = []
    for k in range(len(BOUNDS) - 1):
        if k == 0:
            labels.append(T("seg_holding"))
            continue
        turn = (WAYPOINTS[k][1] - WAYPOINTS[k - 1][1] + 180.0) % 360.0 - 180.0
        labels.append(T("seg_holding") if abs(turn) < 1e-6
                      else f"{T('seg_turn')} {turn:+.0f}°")
    return labels


