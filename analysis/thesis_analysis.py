def load_data():
    """Load heading time-series.  Returns (t, ref_deg, controllers_dict).

    controllers_dict maps controller name -> {heading_cont_deg, err_deg}.
    """
    import pandas as pd

    three_way_path = os.path.join(OUTDIR, "patch_compare_timeseries.csv")
    two_way_path   = os.path.join(RESULTS, "s6_kursa_kludas_analize.csv")

    if os.path.exists(three_way_path):
        print(f"[thesis_analysis] Loading 3-way data from {three_way_path}")
        df = pd.read_csv(three_way_path)
        t = df["time_s"].values
        ref_deg = df["reference_cont_deg"].values
        ctrl_names = [
            "PID (tuned)",
            "NMPC traj. (N=12)",
            "NMPC offset-free (N=12)",
        ]
        controllers = {}
        for n in ctrl_names:
            cont_col = f"{n}_cont_deg"
            err_col  = f"{n}_err_deg"
            if cont_col in df.columns and err_col in df.columns:
                controllers[n] = {
                    "heading_cont_deg": df[cont_col].values,
                    "err_deg": df[err_col].values,
                }
        # The patch CSV has no Fossen builtin run; merge it from the
        # scenario-6 CSV (same seed/current realisation, same time grid)
        # so the deep-dive figures include the baseline.  Put it first so
        # it draws underneath the controllers of interest.
        if os.path.exists(two_way_path):
            df6 = pd.read_csv(two_way_path)
            pfx = "Fossen_PID/SMC"
            cont_col = f"{pfx}_heading_continuous_deg"
            err_col = f"{pfx}_heading_error_deg"
            if (cont_col in df6.columns and err_col in df6.columns
                    and len(df6) == len(df)):
                controllers = {
                    "Fossen PID/SMC": {
                        "heading_cont_deg": df6[cont_col].values,
                        "err_deg": df6[err_col].values,
                    },
                    **controllers,
                }
        return t, ref_deg, controllers

    if os.path.exists(two_way_path):
        print(f"[thesis_analysis] Loading 2-way data from {two_way_path}")
        df = pd.read_csv(two_way_path)
        t = df["time_s"].values
        ref_deg = df["reference_heading_continuous_deg"].values
        # Map stable internal names to CSV column prefixes
        col_map = {
            "Fossen PID/SMC":          "Fossen_PID/SMC",
            "PID (tuned)":             "PID_tuned",
            "PID (5 Hz)":              "PID_5_Hz",
            "NMPC offset-free (N=12)": "NMPC_offset-free_N12",
        }
        controllers = {}
        for name, pfx in col_map.items():
            cont_col = f"{pfx}_heading_continuous_deg"
            err_col  = f"{pfx}_heading_error_deg"
            if cont_col in df.columns and err_col in df.columns:
                controllers[name] = {
                    "heading_cont_deg": df[cont_col].values,
                    "err_deg": df[err_col].values,
                }
        return t, ref_deg, controllers

    raise FileNotFoundError(
        "No input CSV found.  Run one of:\n"
        "  python -m experiments.run_remus100_comparison\n"
        "  python -m analysis.compare_nmpc_patch")


# --------------------------------------------------------------------------- #
#  Performance metrics
# --------------------------------------------------------------------------- #
def compute_full_metrics(t, ref_deg, controllers):
    """Compute RMSE/MAE/IAE/ITAE/P95/P99/max across three regimes per controller.

    Returns nested dict: {name -> {'aggregate'|'transient'|'settled' -> {metric -> value}}}
    """
    ref_rad = ref_deg * D2R
    changing = [WAYPOINTS[i + 1][1] != WAYPOINTS[i][1] for i in range(len(SWITCH))]

    # Settled mask: last 40% of each segment
    settled_mask = np.zeros(len(t), bool)
    for a, b in zip(BOUNDS[:-1], BOUNDS[1:]):
        settled_mask |= (t >= a + 0.6 * (b - a)) & (t < b)

    out = {}
    for name, d in controllers.items():
        sig_rad = d["heading_cont_deg"] * D2R
        e_abs = np.abs(M.angle_error(sig_rad, ref_rad)) * R2D
        tm = M.tracking_metrics(t, sig_rad, ref_rad, angular=True)
        sp = M.split_transient_steady(t, sig_rad, ref_rad, SWITCH,
                                      angular=True, transient_window=35.0,
                                      only_changing=changing)
        e_full = M.angle_error(sig_rad, ref_rad) * R2D

        def _regime_metrics(mask):
            if not mask.any():
                return {k: float("nan") for k in
                        ("rmse", "mae", "iae", "itae", "p95", "p99", "max")}
            ea = np.abs(e_full[mask])
            return {
                "rmse": float(np.sqrt(np.mean(e_full[mask] ** 2))),
                "mae":  float(np.mean(ea)),
                "iae":  float(np.sum(ea) * float(np.median(np.diff(t)))),
                "itae": float(np.sum(t[mask] * ea) * float(np.median(np.diff(t)))),
                "p95":  float(np.percentile(ea, 95)),
                "p99":  float(np.percentile(ea, 99)),
                "max":  float(np.max(ea)),
            }

        # Transient mask: ±35 s after heading-changing waypoints
        trans_mask = np.zeros(len(t), bool)
        for i, ts in enumerate(SWITCH):
            if changing[i]:
                trans_mask |= (t >= ts) & (t < ts + 35.0)

        out[name] = {
            "aggregate": _regime_metrics(np.ones(len(t), bool)),
            "transient": _regime_metrics(trans_mask),
            "settled":   _regime_metrics(settled_mask),
        }
    return out


# --------------------------------------------------------------------------- #
#  Root cause analysis
# --------------------------------------------------------------------------- #
def root_cause_analysis(t, ref_deg, controllers, full_metrics):
    """Quantify the two NMPC failure modes.

    For each controller, compute the IAE contribution from each failure window
    and express it as a fraction of the total mission IAE.
    """
    dt = float(np.median(np.diff(t)))
    findings = {}
    for name, d in controllers.items():
        total_iae = full_metrics[name]["aggregate"]["iae"]
        entry = {}
        for label, window in [("depth_coupling", WIN_DEPTH),
                               ("reversal",       WIN_REVERSAL)]:
            mask = (t >= window[0]) & (t < window[1])
            if not mask.any():
                entry[label] = {"window_iae": 0.0, "pct": 0.0, "peak_deg": 0.0}
                continue
            w_iae = float(np.sum(np.abs(d["err_deg"][mask])) * dt)
            peak  = float(np.max(np.abs(d["err_deg"][mask])))
            entry[label] = {
                "window_iae": w_iae,
                "pct":        100.0 * w_iae / max(total_iae, 1e-9),
                "peak_deg":   peak,
            }
        findings[name] = entry
    return findings


